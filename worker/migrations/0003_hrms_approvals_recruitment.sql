-- HRMS-only approval, recruitment and employee document metadata.
-- Store uploaded file bytes in private object storage; never in this table.
BEGIN;

CREATE TABLE IF NOT EXISTS hrms_approval_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_number VARCHAR(30) NOT NULL UNIQUE,
  requester_id BIGINT NOT NULL REFERENCES hrms_employees(id) ON DELETE RESTRICT,
  subject VARCHAR(180) NOT NULL,
  details TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  current_step SMALLINT NOT NULL DEFAULT 1 CHECK (current_step >= 1),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS hrms_approval_steps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT NOT NULL REFERENCES hrms_approval_requests(id) ON DELETE CASCADE,
  sequence SMALLINT NOT NULL CHECK (sequence >= 1),
  role VARCHAR(20) NOT NULL CHECK (role IN ('manager','hr','gm')),
  approver_id BIGINT NULL REFERENCES hrms_employees(id) ON DELETE RESTRICT,
  decision VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (decision IN ('pending','approved','rejected')),
  comment TEXT NOT NULL DEFAULT '',
  decided_at TIMESTAMPTZ NULL,
  UNIQUE(request_id, sequence)
);

CREATE TABLE IF NOT EXISTS hrms_recruitment_candidates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(180) NOT NULL,
  email VARCHAR(254) NOT NULL DEFAULT '',
  phone VARCHAR(40) NOT NULL DEFAULT '',
  position_id BIGINT NULL REFERENCES hrms_job_positions(id) ON DELETE RESTRICT,
  source VARCHAR(100) NOT NULL DEFAULT '',
  applied_at DATE NULL,
  stage VARCHAR(20) NOT NULL DEFAULT 'new' CHECK (stage IN ('new','screening','interview','offer','hired','rejected','withdrawn')),
  expected_salary NUMERIC(12,2) NULL CHECK (expected_salary IS NULL OR expected_salary >= 0),
  notes TEXT NOT NULL DEFAULT '',
  hired_employee_id BIGINT NULL REFERENCES hrms_employees(id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS hrms_recruitment_stage_idx ON hrms_recruitment_candidates(stage, created_at DESC);

CREATE TABLE IF NOT EXISTS hrms_employee_documents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL REFERENCES hrms_employees(id) ON DELETE CASCADE,
  title VARCHAR(160) NOT NULL,
  document_type VARCHAR(60) NOT NULL,
  object_key TEXT NOT NULL UNIQUE,
  issue_date DATE NULL,
  expiry_date DATE NULL,
  uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (expiry_date IS NULL OR issue_date IS NULL OR expiry_date >= issue_date)
);

CREATE TABLE IF NOT EXISTS hrms_skills (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(160) NOT NULL UNIQUE,
  category VARCHAR(80) NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS hrms_employee_skills (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL REFERENCES hrms_employees(id) ON DELETE CASCADE,
  skill_id BIGINT NOT NULL REFERENCES hrms_skills(id) ON DELETE RESTRICT,
  level SMALLINT NOT NULL CHECK (level BETWEEN 1 AND 5),
  assessed_at DATE NOT NULL DEFAULT CURRENT_DATE,
  evidence TEXT NOT NULL DEFAULT '',
  next_review_date DATE NULL,
  UNIQUE(employee_id, skill_id)
);

INSERT INTO hrms_schema_migrations(version)
VALUES ('0003_hrms_approvals_recruitment')
ON CONFLICT (version) DO NOTHING;

COMMIT;

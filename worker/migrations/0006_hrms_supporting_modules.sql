CREATE TABLE IF NOT EXISTS hrms_employee_fund_policies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(160) NOT NULL,
  emergency_share_percent NUMERIC(5,2) NOT NULL DEFAULT 10 CHECK (emergency_share_percent BETWEEN 0 AND 100),
  association_share_percent NUMERIC(5,2) NOT NULL DEFAULT 90 CHECK (association_share_percent BETWEEN 0 AND 100),
  effective_from DATE NOT NULL,
  effective_to DATE NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  requires_approval BOOLEAN NOT NULL DEFAULT TRUE,
  notes TEXT NOT NULL DEFAULT '',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (emergency_share_percent + association_share_percent = 100),
  CHECK (effective_to IS NULL OR effective_to >= effective_from)
);


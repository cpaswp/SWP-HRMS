CREATE TABLE IF NOT EXISTS hrms_employee_advances (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL REFERENCES hrms_employees(id) ON DELETE RESTRICT,
  policy_id BIGINT NULL REFERENCES hrms_advance_policies(id) ON DELETE RESTRICT,
  requested_amount NUMERIC(12,2) NOT NULL CHECK (requested_amount > 0),
  approved_amount NUMERIC(12,2) NULL CHECK (approved_amount IS NULL OR approved_amount >= 0),
  installments SMALLINT NOT NULL DEFAULT 1 CHECK (installments >= 1),
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  approval_request_id BIGINT NULL REFERENCES hrms_approval_requests(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  notes TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS hrms_custody_assets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_code VARCHAR(60) NOT NULL UNIQUE,

CREATE TABLE IF NOT EXISTS hrms_insurance_form_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL REFERENCES hrms_employees(id) ON DELETE RESTRICT,
  form_type VARCHAR(8) NOT NULL,
  reference_number VARCHAR(80) NOT NULL DEFAULT '',
  effective_date DATE NOT NULL,
  submitted_at DATE NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'draft',
  object_key TEXT NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS hrms_internal_regulations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE,
  title VARCHAR(180) NOT NULL,
  category VARCHAR(80) NOT NULL,
  description TEXT NOT NULL,
  effective_from DATE NOT NULL,
  effective_to DATE NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  object_key TEXT NOT NULL DEFAULT '',
  CHECK (effective_to IS NULL OR effective_to >= effective_from)
);

CREATE TABLE IF NOT EXISTS hrms_disciplinary_actions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL REFERENCES hrms_employees(id) ON DELETE RESTRICT,
  regulation_id BIGINT NOT NULL REFERENCES hrms_internal_regulations(id) ON DELETE RESTRICT,
  incident_date DATE NOT NULL,
  description TEXT NOT NULL,
  investigation_notes TEXT NOT NULL DEFAULT '',
  proposed_action VARCHAR(180) NOT NULL,
  deduction_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (deduction_amount >= 0),
  status VARCHAR(20) NOT NULL DEFAULT 'investigation',
  approval_request_id BIGINT NULL REFERENCES hrms_approval_requests(id) ON DELETE SET NULL,
  deduction_id BIGINT NULL REFERENCES hrms_employee_deductions(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS hrms_training_courses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE,
  title VARCHAR(180) NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  provider VARCHAR(180) NOT NULL DEFAULT '',
  start_date DATE NULL,
  end_date DATE NULL,
  cost NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (cost >= 0),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS hrms_employee_training (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  membership_id BIGINT NOT NULL REFERENCES hrms_employee_fund_memberships(id) ON DELETE RESTRICT,
  period_id BIGINT NOT NULL REFERENCES hrms_payroll_periods(id) ON DELETE RESTRICT,
  gross_amount NUMERIC(12,2) NOT NULL CHECK (gross_amount >= 0),
  emergency_amount NUMERIC(12,2) NOT NULL CHECK (emergency_amount >= 0),
  association_amount NUMERIC(12,2) NOT NULL CHECK (association_amount >= 0),

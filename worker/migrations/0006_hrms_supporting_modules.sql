  position_id BIGINT NULL REFERENCES hrms_job_positions(id) ON DELETE RESTRICT,
  plan_year SMALLINT NOT NULL CHECK (plan_year BETWEEN 1900 AND 2200),
  planned_headcount INTEGER NOT NULL DEFAULT 0 CHECK (planned_headcount >= 0),
  approved_headcount INTEGER NOT NULL DEFAULT 0 CHECK (approved_headcount >= 0),
  notes TEXT NOT NULL DEFAULT '',
  UNIQUE(department_id, position_id, plan_year)
);

CREATE TABLE IF NOT EXISTS hrms_advance_policies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE,

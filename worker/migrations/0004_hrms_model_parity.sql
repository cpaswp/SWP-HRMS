-- HRMS model-parity increment: hierarchy and employee mission/attendance exceptions.
-- Apply only after 0001-0003 on the dedicated HRMS test database.
BEGIN;

ALTER TABLE hrms_departments
  ADD COLUMN IF NOT EXISTS manager_id BIGINT NULL REFERENCES hrms_employees(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS hrms_mission_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL REFERENCES hrms_employees(id) ON DELETE RESTRICT,
  destination VARCHAR(180) NOT NULL,
  purpose TEXT NOT NULL,
  start_at TIMESTAMPTZ NOT NULL,
  end_at TIMESTAMPTZ NOT NULL,
  transport_allowance NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (transport_allowance >= 0),
  per_diem NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (per_diem >= 0),
  status VARCHAR(20) NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft','pending','approved','rejected','completed')),
  approval_request_id BIGINT NULL REFERENCES hrms_approval_requests(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (end_at >= start_at)
);
CREATE INDEX IF NOT EXISTS hrms_missions_employee_start_idx
  ON hrms_mission_requests(employee_id, start_at DESC);

CREATE TABLE IF NOT EXISTS hrms_attendance_exceptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL REFERENCES hrms_employees(id) ON DELETE RESTRICT,
  work_date DATE NOT NULL,
  kind VARCHAR(20) NOT NULL CHECK (kind IN ('late','early','absence','overtime','manual')),
  minutes INTEGER NOT NULL DEFAULT 0 CHECK (minutes >= 0),
  reason TEXT NOT NULL DEFAULT '',
  excused BOOLEAN NOT NULL DEFAULT FALSE,
  approval_request_id BIGINT NULL REFERENCES hrms_approval_requests(id) ON DELETE SET NULL,
  payroll_item_id BIGINT NULL REFERENCES hrms_payroll_items(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS hrms_attendance_exceptions_employee_date_idx
  ON hrms_attendance_exceptions(employee_id, work_date DESC);

INSERT INTO hrms_schema_migrations(version)
VALUES ('0004_hrms_model_parity')
ON CONFLICT (version) DO NOTHING;

COMMIT;

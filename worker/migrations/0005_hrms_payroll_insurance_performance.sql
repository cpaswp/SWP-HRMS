-- HRMS compensation, insurance and performance foundations.
-- Apply only after migrations 0001-0004 on the dedicated HRMS test database.
BEGIN;

CREATE TABLE IF NOT EXISTS hrms_employee_insurance_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL UNIQUE REFERENCES hrms_employees(id) ON DELETE RESTRICT,
  insurance_number VARCHAR(40) NOT NULL DEFAULT '',
  establishment_number VARCHAR(40) NOT NULL DEFAULT '',
  insured_salary NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (insured_salary >= 0),
  start_date DATE NULL,
  end_date DATE NULL,
  office VARCHAR(160) NOT NULL DEFAULT '',
  status VARCHAR(40) NOT NULL DEFAULT 'pending',
  notes TEXT NOT NULL DEFAULT '',
  CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);
CREATE INDEX IF NOT EXISTS hrms_insurance_number_idx ON hrms_employee_insurance_records(insurance_number);

CREATE TABLE IF NOT EXISTS hrms_payroll_components (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(30) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  kind VARCHAR(20) NOT NULL CHECK (kind IN ('earning','deduction')),
  taxable BOOLEAN NOT NULL DEFAULT TRUE,
  insurable BOOLEAN NOT NULL DEFAULT TRUE,
  recurring BOOLEAN NOT NULL DEFAULT FALSE,
  active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS hrms_employee_deductions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL REFERENCES hrms_employees(id) ON DELETE RESTRICT,
  component_id BIGINT NULL REFERENCES hrms_payroll_components(id) ON DELETE RESTRICT,
  kind VARCHAR(20) NOT NULL,
  amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
  effective_date DATE NOT NULL,
  installments SMALLINT NOT NULL DEFAULT 1 CHECK (installments >= 1),
  remaining_installments SMALLINT NOT NULL DEFAULT 1 CHECK (remaining_installments >= 0),
  reason TEXT NOT NULL,
  approval_request_id BIGINT NULL REFERENCES hrms_approval_requests(id) ON DELETE RESTRICT,
  active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX IF NOT EXISTS hrms_employee_deductions_active_idx
  ON hrms_employee_deductions(employee_id, active, effective_date);

CREATE TABLE IF NOT EXISTS hrms_salary_changes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL REFERENCES hrms_employees(id) ON DELETE RESTRICT,
  change_type VARCHAR(20) NOT NULL,
  effective_date DATE NOT NULL,
  old_salary NUMERIC(12,2) NOT NULL CHECK (old_salary >= 0),
  new_salary NUMERIC(12,2) NOT NULL CHECK (new_salary >= 0),
  percentage NUMERIC(7,3) NOT NULL DEFAULT 0,
  reason TEXT NOT NULL,
  approval_request_id BIGINT NOT NULL REFERENCES hrms_approval_requests(id) ON DELETE RESTRICT,
  applied BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS hrms_salary_changes_employee_effective_idx
  ON hrms_salary_changes(employee_id, effective_date DESC);

CREATE TABLE IF NOT EXISTS hrms_kpis (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(30) NOT NULL UNIQUE,
  name VARCHAR(160) NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  weight_percent NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (weight_percent BETWEEN 0 AND 100),
  active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS hrms_performance_reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL REFERENCES hrms_employees(id) ON DELETE RESTRICT,
  reviewer_id BIGINT NOT NULL REFERENCES hrms_employees(id) ON DELETE RESTRICT,
  period_start DATE NOT NULL,
  period_end DATE NOT NULL,
  performance_score NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (performance_score BETWEEN 0 AND 100),
  behavior_score NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (behavior_score BETWEEN 0 AND 100),
  appearance_score NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (appearance_score BETWEEN 0 AND 100),
  commitment_score NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (commitment_score BETWEEN 0 AND 100),
  overall_score NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (overall_score BETWEEN 0 AND 100),
  strengths TEXT NOT NULL DEFAULT '',
  improvement_plan TEXT NOT NULL DEFAULT '',
  status VARCHAR(20) NOT NULL DEFAULT 'draft',
  approval_request_id BIGINT NULL REFERENCES hrms_approval_requests(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (period_end >= period_start)
);
CREATE INDEX IF NOT EXISTS hrms_performance_employee_period_idx
  ON hrms_performance_reviews(employee_id, period_start DESC);

INSERT INTO hrms_schema_migrations(version)
VALUES ('0005_hrms_payroll_insurance_performance')
ON CONFLICT (version) DO NOTHING;

COMMIT;

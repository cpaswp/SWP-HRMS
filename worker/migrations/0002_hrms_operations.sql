-- HRMS-only operational tables. Apply only to the dedicated HRMS test database.
-- Additive, idempotent migration; does not touch ERP objects.
BEGIN;

CREATE TABLE IF NOT EXISTS hrms_attendance_sites (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  latitude NUMERIC(10,7) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
  longitude NUMERIC(10,7) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
  radius_meters SMALLINT NOT NULL DEFAULT 50 CHECK (radius_meters BETWEEN 1 AND 500),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS hrms_attendance_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL REFERENCES hrms_employees(id) ON DELETE RESTRICT,
  site_id BIGINT NULL REFERENCES hrms_attendance_sites(id) ON DELETE RESTRICT,
  kind VARCHAR(3) NOT NULL CHECK (kind IN ('in','out')),
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  latitude NUMERIC(10,7) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
  longitude NUMERIC(10,7) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
  distance_meters NUMERIC(8,2) NULL CHECK (distance_meters IS NULL OR distance_meters >= 0),
  face_verified BOOLEAN NOT NULL DEFAULT FALSE,
  face_provider_ref VARCHAR(160) NOT NULL DEFAULT '',
  device_fingerprint VARCHAR(160) NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS hrms_attendance_employee_time_idx ON hrms_attendance_records(employee_id, recorded_at DESC);

CREATE TABLE IF NOT EXISTS hrms_leave_policies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(24) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  annual_entitlement_days NUMERIC(6,2) NOT NULL DEFAULT 0 CHECK (annual_entitlement_days >= 0),
  carry_forward_limit_days NUMERIC(6,2) NOT NULL DEFAULT 0 CHECK (carry_forward_limit_days >= 0),
  paid BOOLEAN NOT NULL DEFAULT TRUE,
  requires_document BOOLEAN NOT NULL DEFAULT FALSE,
  active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS hrms_leave_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL REFERENCES hrms_employees(id) ON DELETE RESTRICT,
  leave_type VARCHAR(50) NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  reason TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','pending','approved','rejected','cancelled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (end_date >= start_date)
);
CREATE INDEX IF NOT EXISTS hrms_leave_employee_status_idx ON hrms_leave_requests(employee_id, status);

CREATE TABLE IF NOT EXISTS hrms_employee_leave_balances (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL REFERENCES hrms_employees(id) ON DELETE RESTRICT,
  policy_id BIGINT NOT NULL REFERENCES hrms_leave_policies(id) ON DELETE RESTRICT,
  year SMALLINT NOT NULL CHECK (year BETWEEN 1900 AND 2200),
  opening_days NUMERIC(7,2) NOT NULL DEFAULT 0,
  accrued_days NUMERIC(7,2) NOT NULL DEFAULT 0 CHECK (accrued_days >= 0),
  used_days NUMERIC(7,2) NOT NULL DEFAULT 0 CHECK (used_days >= 0),
  adjusted_days NUMERIC(7,2) NOT NULL DEFAULT 0,
  UNIQUE(employee_id, policy_id, year)
);

CREATE TABLE IF NOT EXISTS hrms_payroll_periods (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','review','approved','paid')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS hrms_payroll_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period_id BIGINT NOT NULL REFERENCES hrms_payroll_periods(id) ON DELETE CASCADE,
  employee_id BIGINT NOT NULL REFERENCES hrms_employees(id) ON DELETE RESTRICT,
  basic_salary NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (basic_salary >= 0),
  allowances NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (allowances >= 0),
  overtime NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (overtime >= 0),
  deductions NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (deductions >= 0),
  tax_and_insurance NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (tax_and_insurance >= 0),
  net_salary NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (net_salary >= 0),
  UNIQUE(period_id, employee_id)
);

INSERT INTO hrms_schema_migrations(version)
VALUES ('0002_hrms_operations')
ON CONFLICT (version) DO NOTHING;

COMMIT;

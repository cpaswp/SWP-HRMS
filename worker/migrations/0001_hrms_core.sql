-- HRMS-only schema. Additive and namespaced to avoid collisions with ERP tables.
-- Apply only to a dedicated HRMS test database; never point this migration at ERP.
BEGIN;

CREATE TABLE IF NOT EXISTS hrms_schema_migrations (
  version TEXT PRIMARY KEY,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS hrms_departments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(20) NOT NULL UNIQUE,
  name VARCHAR(160) NOT NULL,
  parent_id BIGINT NULL REFERENCES hrms_departments(id) ON DELETE RESTRICT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS hrms_job_positions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(20) NOT NULL UNIQUE,
  title VARCHAR(160) NOT NULL,
  department_id BIGINT NOT NULL REFERENCES hrms_departments(id) ON DELETE RESTRICT,
  job_description TEXT NOT NULL DEFAULT '',
  responsibilities TEXT NOT NULL DEFAULT '',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS hrms_employees (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_code VARCHAR(30) NOT NULL UNIQUE,
  full_name VARCHAR(180) NOT NULL,
  email VARCHAR(254) NOT NULL DEFAULT '',
  phone VARCHAR(40) NOT NULL DEFAULT '',
  address TEXT NOT NULL DEFAULT '',
  date_of_birth DATE NULL,
  hire_date DATE NULL,
  department_id BIGINT NULL REFERENCES hrms_departments(id) ON DELETE RESTRICT,
  position_id BIGINT NULL REFERENCES hrms_job_positions(id) ON DELETE RESTRICT,
  manager_id BIGINT NULL REFERENCES hrms_employees(id) ON DELETE SET NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'active'
    CHECK (status IN ('active','leave','suspended','terminated')),
  base_salary NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (base_salary >= 0),
  emergency_contact VARCHAR(160) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS hrms_employees_department_idx ON hrms_employees(department_id);
CREATE INDEX IF NOT EXISTS hrms_employees_status_idx ON hrms_employees(status);
CREATE INDEX IF NOT EXISTS hrms_job_positions_department_idx ON hrms_job_positions(department_id);

INSERT INTO hrms_schema_migrations(version)
VALUES ('0001_hrms_core')
ON CONFLICT (version) DO NOTHING;

COMMIT;
